CREATE TABLE salas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    tipo VARCHAR(100) NOT NULL,
    capacidade INTEGER NOT NULL,
    localizacao VARCHAR(255) NOT NULL,
    restrita BOOLEAN NOT NULL,
    ativa BOOLEAN NOT NULL,
    CONSTRAINT ck_salas_nome_nao_vazio CHECK (char_length(trim(nome)) > 0),
    CONSTRAINT ck_salas_tipo_nao_vazio CHECK (char_length(trim(tipo)) > 0),
    CONSTRAINT ck_salas_capacidade_positiva CHECK (capacidade > 0),
    CONSTRAINT ck_salas_localizacao_nao_vazia CHECK (char_length(trim(localizacao)) > 0)
);
