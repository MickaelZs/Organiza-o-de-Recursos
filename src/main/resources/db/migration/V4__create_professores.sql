CREATE TABLE professores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    competencia VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL,
    CONSTRAINT uk_professores_email UNIQUE (email),
    CONSTRAINT ck_professores_nome_nao_vazio CHECK (char_length(trim(nome)) > 0),
    CONSTRAINT ck_professores_email_nao_vazio CHECK (char_length(trim(email)) > 0),
    CONSTRAINT ck_professores_competencia_nao_vazia CHECK (char_length(trim(competencia)) > 0)
);
