CREATE TABLE manutencoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_recurso VARCHAR(20) NOT NULL,
    sala_id BIGINT,
    professor_id BIGINT,
    material_id BIGINT,
    inicio TIMESTAMP WITH TIME ZONE NOT NULL,
    termino TIMESTAMP WITH TIME ZONE NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    responsavel_id BIGINT NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_manutencoes_sala FOREIGN KEY (sala_id) REFERENCES salas (id) ON DELETE CASCADE,
    CONSTRAINT fk_manutencoes_professor FOREIGN KEY (professor_id) REFERENCES professores (id) ON DELETE CASCADE,
    CONSTRAINT fk_manutencoes_material FOREIGN KEY (material_id) REFERENCES materiais (id) ON DELETE CASCADE,
    CONSTRAINT fk_manutencoes_responsavel FOREIGN KEY (responsavel_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT ck_manutencoes_exatamente_um_recurso CHECK (
        (CASE WHEN sala_id IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN professor_id IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN material_id IS NOT NULL THEN 1 ELSE 0 END) = 1
    ),
    CONSTRAINT ck_manutencoes_termino_posterior_inicio CHECK (termino > inicio),
    CONSTRAINT ck_manutencoes_tipo_recurso CHECK (tipo_recurso IN ('SALA', 'PROFESSOR', 'MATERIAL')),
    CONSTRAINT ck_manutencoes_status CHECK (status IN ('ATIVA', 'CANCELADA'))
);
