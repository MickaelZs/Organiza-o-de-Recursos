CREATE TABLE materiais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    tipo VARCHAR(100) NOT NULL,
    quantidade_total INTEGER NOT NULL,
    quantidade_disponivel INTEGER NOT NULL,
    localizacao VARCHAR(255) NOT NULL,
    restrito BOOLEAN NOT NULL,
    ativo BOOLEAN NOT NULL,
    CONSTRAINT ck_materiais_nome_nao_vazio CHECK (char_length(trim(nome)) > 0),
    CONSTRAINT ck_materiais_tipo_nao_vazio CHECK (char_length(trim(tipo)) > 0),
    CONSTRAINT ck_materiais_localizacao_nao_vazia CHECK (char_length(trim(localizacao)) > 0),
    CONSTRAINT ck_materiais_quantidade_total_nao_negativa CHECK (quantidade_total >= 0),
    CONSTRAINT ck_materiais_quantidade_disponivel_nao_negativa CHECK (quantidade_disponivel >= 0),
    CONSTRAINT ck_materiais_quantidade_disponivel_valida CHECK (quantidade_disponivel <= quantidade_total)
);
