CREATE TABLE reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id BIGINT NOT NULL,
    sala_id BIGINT,
    professor_id BIGINT,
    material_id BIGINT,
    inicio TIMESTAMP WITH TIME ZONE NOT NULL,
    termino TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_reservas_solicitante FOREIGN KEY (solicitante_id) REFERENCES usuarios (id),
    CONSTRAINT fk_reservas_sala FOREIGN KEY (sala_id) REFERENCES salas (id),
    CONSTRAINT fk_reservas_professor FOREIGN KEY (professor_id) REFERENCES professores (id),
    CONSTRAINT fk_reservas_material FOREIGN KEY (material_id) REFERENCES materiais (id),
    CONSTRAINT ck_reservas_exatamente_um_recurso CHECK (
        (CASE WHEN sala_id IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN professor_id IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN material_id IS NOT NULL THEN 1 ELSE 0 END) = 1
    ),
    CONSTRAINT ck_reservas_termino_posterior_inicio CHECK (termino > inicio),
    CONSTRAINT ck_reservas_status CHECK (status IN (
        'SOLICITADA', 'APROVADA', 'EM_USO', 'CONCLUIDA', 'REJEITADA', 'CANCELADA', 'NAO_COMPARECEU'
    ))
);
